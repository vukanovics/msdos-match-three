#!/usr/bin/env python3
"""Convert the match-three sprite sheet into a C header of palette indices.

The DJGPP target has no PNG library, so the sheet is baked into the game as a
256-colour palette plus 8-bit index data for each tile.

Usage: png_to_tiles.py <sheet.png> <output.h>
"""

import sys

from PIL import Image

TILE_WIDTH = 24
TILE_HEIGHT = 24
TILE_COUNT = 6

# Reserve the last two palette entries for the game's UI (cursor / picked).
COLOR_COUNT = 254
CURSOR_INDEX = 254
PICKED_INDEX = 255


def as_c_array(values, per_line):
    lines = []
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(str(value) for value in chunk) + ",")
    return lines


def main(sprite_path, output_path):
    sheet = Image.open(sprite_path).convert("RGBA")

    # Composite the transparency onto black, then reduce to a shared palette.
    background = Image.new("RGBA", sheet.size, (0, 0, 0, 255))
    sheet = Image.alpha_composite(background, sheet).convert("RGB")
    sheet = sheet.quantize(colors=COLOR_COUNT, method=Image.Quantize.MEDIANCUT)

    palette = sheet.getpalette()[: COLOR_COUNT * 3]
    palette += [0] * (256 * 3 - len(palette))
    palette[CURSOR_INDEX * 3:CURSOR_INDEX * 3 + 3] = [255, 255, 255]
    palette[PICKED_INDEX * 3:PICKED_INDEX * 3 + 3] = [255, 0, 0]

    pixels = sheet.tobytes()
    stride = sheet.width

    lines = []
    lines.append("#ifndef MATCH3_TILES_H_INCLUDED")
    lines.append("#define MATCH3_TILES_H_INCLUDED")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("// Generated by tools/png_to_tiles.py; do not edit.")
    lines.append("")
    lines.append("#define MATCH3_TILE_COUNT %d" % TILE_COUNT)
    lines.append("#define MATCH3_TILE_WIDTH %d" % TILE_WIDTH)
    lines.append("#define MATCH3_TILE_HEIGHT %d" % TILE_HEIGHT)
    lines.append("#define MATCH3_CURSOR_COLOR %d" % CURSOR_INDEX)
    lines.append("#define MATCH3_PICKED_COLOR %d" % PICKED_INDEX)
    lines.append("")
    lines.append("static const uint8_t match3_palette[256][3] = {")
    for index in range(256):
        red, green, blue = palette[index * 3:index * 3 + 3]
        lines.append("    {%d, %d, %d}," % (red, green, blue))
    lines.append("};")
    lines.append("")
    lines.append("static const uint8_t match3_tiles"
                 "[MATCH3_TILE_COUNT]"
                 "[MATCH3_TILE_WIDTH * MATCH3_TILE_HEIGHT] = {")
    for tile in range(TILE_COUNT):
        lines.append("    {")
        for y in range(TILE_HEIGHT):
            row = [pixels[y * stride + tile * TILE_WIDTH + x]
                   for x in range(TILE_WIDTH)]
            lines.append("        " + ", ".join(str(value) for value in row) + ",")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(output_path, "w") as output:
        output.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.stderr.write("usage: png_to_tiles.py <sheet.png> <output.h>\n")
        sys.exit(1)
    main(sys.argv[1], sys.argv[2])
